#!/usr/bin/env python3
"""Automated 3-phase onboarding and lock updater for rules_dnfo.

Orchestrates:
1. Gazelle to generate BUILD.bazel skeleton with lock_only = True.
2. Bazel query to discover lock targets generated by dnfo_image.
3. Bazel run on companion .lock targets to generate/refresh lockfiles via dnf5-prebuilt.
4. Buildozer to register dnfo.lock and use_repo in MODULE.bazel.
5. Second Gazelle run to flip lock_only to False.
6. Third Gazelle run to verify idempotency.
"""

import os
import subprocess
import sys
import xml.etree.ElementTree as ET

def log(msg):
    print(f"[dnfo:update] {msg}")

def find_buildozer():
    rpath = os.environ.get("BUILDOZER_BIN")
    if not rpath:
        raise RuntimeError("BUILDOZER_BIN environment variable is not set")

    runfiles_dir = os.environ.get("RUNFILES_DIR")
    if not runfiles_dir:
        base = sys.argv[0]
        if os.path.isdir(base + ".runfiles"):
            runfiles_dir = base + ".runfiles"

    if runfiles_dir:
        p = os.path.join(runfiles_dir, rpath)
        if os.path.isfile(p):
            return p

    raise RuntimeError(f"Could not locate {rpath} in runfiles ({runfiles_dir})")

def run_bazel(cmd_args, cwd):
    full_cmd = ["bazel"] + cmd_args
    log(f"Running: {' '.join(full_cmd)}")
    res = subprocess.run(full_cmd, cwd=cwd, text=True)
    if res.returncode != 0:
        log(f"Command failed with exit code {res.returncode}")
        sys.exit(res.returncode)

def discover_lock_targets(workspace_root):
    """Uses bazel query to discover all .lock targets generated by dnfo_image."""
    query_cmd = [
        "bazel",
        "query",
        'attr(name, ".*\\.lock$", attr(generator_function, dnfo_image, //...))',
        "--output=xml",
    ]
    log(f"Discovering lock targets via Bazel query...")
    try:
        xml_out = subprocess.check_output(query_cmd, cwd=workspace_root, text=True)
    except subprocess.CalledProcessError as e:
        log(f"Bazel query failed with exit code {e.returncode}")
        sys.exit(e.returncode)

    targets = []
    root = ET.fromstring(xml_out)
    for rule in root.findall("rule"):
        lock_target = rule.get("name")
        gen_elem = rule.find("./string[@name='generator_name']")
        target_name = gen_elem.get("value")
        out_elem = rule.find("./string[@name='out_file']")
        out_file = out_elem.get("value") if out_elem is not None else None

        # Clean out_file to standard repo-relative label format
        if out_file and out_file.startswith("@@//"):
            lock_label = out_file[2:]
        elif out_file and out_file.startswith("//"):
            lock_label = out_file
        else:
            pkg = lock_target.split(":")[0]
            lock_label = f"{pkg}:{target_name}.lock.json"

        repo_name = f"{target_name}_packages"
        targets.append({
            "lock_target": lock_target,
            "target_name": target_name,
            "lock_label": lock_label,
            "repo_name": repo_name,
        })

    return targets

def register_in_module_bazel(module_path, buildozer_bin, repo_name, lock_label):
    # 1. Use buildozer to check if dnfo.lock is already defined
    check = subprocess.run(
        [buildozer_bin, "print name", f"{module_path}:{repo_name}"],
        capture_output=True,
        text=True,
        env=os.environ,
    )
    if repo_name not in check.stdout:
        log(f"Registering dnfo.lock for {repo_name} in MODULE.bazel...")
        subprocess.run(
            [buildozer_bin, f"new dnfo.lock {repo_name}", f"{module_path}:%module"],
            check=True,
            env=os.environ,
        )

    # Set lockfile attribute via buildozer (exit code 0 or 3 means success/already set)
    res = subprocess.run(
        [buildozer_bin, f'set lockfile "{lock_label}"', f"{module_path}:{repo_name}"],
        env=os.environ,
    )
    if res.returncode not in (0, 3):
        log(f"Warning: buildozer set lockfile returned {res.returncode}")

    # 2. Add repo to use_repo via buildozer use_repo_add
    added = False
    for ext_candidate in ["dnfo", "dnfo_test", "@rules_dnfo//dnfo:extensions.bzl dnfo", "//dnfo:extensions.bzl dnfo"]:
        res = subprocess.run(
            [buildozer_bin, f"use_repo_add {ext_candidate} {repo_name}", f"{module_path}:all"],
            capture_output=True,
            text=True,
            env=os.environ,
        )
        if res.returncode in (0, 3):
            added = True
            break

    if not added:
        log(f"Warning: Could not automatically add {repo_name} to use_repo via buildozer")

    # 3. Format MODULE.bazel using buildozer
    subprocess.run([buildozer_bin, "format", f"{module_path}:*"], env=os.environ)

def main():
    workspace_root = os.environ.get("BUILD_WORKSPACE_DIRECTORY", os.getcwd())
    buildozer = find_buildozer()
    log(f"Workspace root: {workspace_root}")
    log(f"Using buildozer: {buildozer}")

    gazelle_target = "@rules_dnfo//dnfo:gazelle"

    # Phase 1: Call gazelle-dnfo to discover configs and generate BUILD.bazel skeleton
    log("=== Phase 1: Generating BUILD.bazel skeleton with gazelle-dnfo ===")
    run_bazel(["run", gazelle_target], cwd=workspace_root)

    # Phase 2: Discover lock targets via Bazel query and run them
    log("=== Phase 2: Discovering and generating lockfiles via dnf5-prebuilt ===")
    lock_targets = discover_lock_targets(workspace_root)
    if not lock_targets:
        log("No dnfo_image lock targets found in workspace.")
        return

    log(f"Discovered {len(lock_targets)} lock target(s): {[t['lock_target'] for t in lock_targets]}")
    for item in lock_targets:
        log(f"Generating lockfile for {item['lock_target']}...")
        run_bazel(["run", item["lock_target"]], cwd=workspace_root)

    # Phase 3: Register lockfiles into MODULE.bazel using buildozer and tidy
    log("=== Phase 3: Registering lockfiles in MODULE.bazel ===")
    module_path = os.path.join(workspace_root, "MODULE.bazel")
    for item in lock_targets:
        register_in_module_bazel(module_path, buildozer, item["repo_name"], item["lock_label"])
    run_bazel(["mod", "tidy"], cwd=workspace_root)

    # Phase 4: Call gazelle-dnfo a second time to flip lock_only to False
    log("=== Phase 4: Flipping lock_only flag with gazelle-dnfo ===")
    run_bazel(["run", gazelle_target], cwd=workspace_root)

    # Phase 5: Call gazelle-dnfo a third time to verify idempotency
    log("=== Phase 5: Verifying idempotency with a 3rd gazelle-dnfo run ===")
    run_bazel(["run", gazelle_target], cwd=workspace_root)

    log("=== dnfo:update completed successfully! ===")

if __name__ == "__main__":
    main()
